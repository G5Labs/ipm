#!/usr/bin/env python3
"""Generate size consumers from the canonical manifest; --check detects drift.

Migration 094 is a forward snapshot. Never rewrite it after publication: add a
new forward migration when changing deployed limits and update the snapshot path.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "backend/g5-contracts/agent-approval-limits.json"
MIGRATION = ROOT / "backend/g5-api/src/db/migrations/094_restore_agent_approval_artifacts.sql"

def generated():
    limits = json.loads(MANIFEST.read_text())
    assert set(limits) == {"version", "output_max_bytes", "frontmatter_max_bytes"}
    assert limits["version"] == 1, "new limit versions require a new forward migration snapshot"
    total, front = limits["output_max_bytes"], limits["frontmatter_max_bytes"]
    assert type(total) is int and type(front) is int and 0 < front < total <= 2147483647
    rust = ("// Generated by scripts/sync-agent-approval-limits.py; edit agent-approval-limits.json.\n"
            f"pub const AGENT_APPROVAL_LIMITS_VERSION: u32 = {limits['version']};\n"
            f"pub const AGENT_APPROVAL_OUTPUT_MAX_BYTES: usize = {total:_};\n"
            f"pub const AGENT_APPROVAL_FRONTMATTER_MAX_BYTES: usize = {front:_};\n")
    paragraph = (f"Write exactly one UTF-8 Markdown file at the platform-supplied path. Write no other file. "
        f"The complete file, including frontmatter, delimiters and body, must be no more than {total // 1024} KiB ({total:,} bytes). "
        f"The raw YAML frontmatter between the delimiters must independently be no more than {front // 1024} KiB ({front:,} bytes). "
        "The Markdown body must be nonblank and fit the remaining complete-file budget; there is no separate body-size cap.")
    skill_path = ROOT / ".agents/skills/g5-agent-approval-review/SKILL.md"
    skill = skill_path.read_text()
    begin, end = "<!-- approval-output-limits:start -->", "<!-- approval-output-limits:end -->"
    before, rest = skill.split(begin, 1)
    _, after = rest.split(end, 1)
    skill = before + begin + "\n" + paragraph + "\n" + end + after
    sql = f"""-- Generated from backend/g5-contracts/agent-approval-limits.json.
-- Forward snapshot: never regenerate a published migration.
-- Artifact storage only. The review coordinator and agent-status writer remain absent.
CREATE FUNCTION public.agent_approval_frontmatter_bytes(document text) RETURNS integer
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT CASE
      WHEN left(document, 4) = E'---\\n'
       AND strpos(substring(document FROM 5), E'\\n---\\n') > 0
      THEN octet_length(split_part(substring(document FROM 5), E'\\n---\\n', 1))
      ELSE -1 END
$$;

CREATE TABLE public.agent_approval_artifacts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id uuid NOT NULL REFERENCES public.orgs(id) ON DELETE CASCADE,
    source_workspace_id uuid NOT NULL,
    approval_request_id uuid NOT NULL,
    task_id uuid NOT NULL,
    result text NOT NULL CHECK (result IN ('approved', 'rejected')),
    document text NOT NULL,
    content_sha256 text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (org_id, source_workspace_id, approval_request_id)
        REFERENCES public.approval_requests(org_id, source_workspace_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, task_id) REFERENCES public.tasks(org_id, id) ON DELETE RESTRICT,
    CONSTRAINT agent_approval_artifacts_output_size
        CHECK (octet_length(document) BETWEEN 1 AND {total}),
    CONSTRAINT agent_approval_artifacts_frontmatter_size
        CHECK (public.agent_approval_frontmatter_bytes(document) BETWEEN 1 AND {front}),
    CONSTRAINT agent_approval_artifacts_digest
        CHECK (content_sha256 = encode(sha256(convert_to(document, 'UTF8')), 'hex'))
);
CREATE INDEX agent_approval_artifacts_request
    ON public.agent_approval_artifacts(org_id, approval_request_id);
ALTER TABLE public.agent_approval_artifacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.agent_approval_artifacts FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON public.agent_approval_artifacts
    USING (org_id = ANY (authz.current_org_ids()))
    WITH CHECK (org_id = ANY (authz.current_org_ids()));
GRANT SELECT, INSERT ON public.agent_approval_artifacts TO g5_tenant;
GRANT SELECT ON public.agent_approval_artifacts TO g5_app;
"""
    system_path = ROOT / "backend/g5-contracts/src/prompts/formal_approval/v1/system.tera"
    system = system_path.read_text()
    prefix = "The skill owns policy interpretation, baseline review dimensions, evidence standards, the exact frontmatter schema, "
    system = system[:system.index(prefix)] + prefix + f"the nonblank body fitting the remaining file budget, the {total // 1024} KiB complete-artifact and independent {front // 1024} KiB raw frontmatter limits, and scoped nonclaims.\n"
    snapshot = ROOT / "backend/g5-contracts/src/prompts/formal_approval/v5"
    guide = (ROOT / ".agents/skills/g5-agent-approval-review/references/agent-prompt.md").read_text()
    consumers = {snapshot / "SKILL.md": skill, snapshot / "agent-prompt.md": guide, system_path: system, ROOT / "backend/g5-contracts/src/types/approval_artifact_limits.rs": rust,
            skill_path: skill, MIGRATION: sql}
    # Older runtimes keep their own instructions; verify only their limit region.
    for version in ("v1", "v2", "v3", "v4"):
        path = ROOT / "backend/g5-contracts/src/prompts/formal_approval" / version / "SKILL.md"
        before, rest = path.read_text().split(begin, 1)
        _, after = rest.split(end, 1)
        consumers[path] = before + begin + "\n" + paragraph + "\n" + end + after
    return consumers

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Generate uncommitted consumers before publication")
    parser.add_argument("--check", action="store_true", help="Fail if any generated consumer differs")
    args = parser.parse_args()
    stale = []
    for path, expected in generated().items():
        if args.write:
            if (path == MIGRATION or any(f"formal_approval/{v}/" in str(path) for v in ("v1","v2","v3","v4","v5"))) and path.exists() and path.read_text() != expected:
                import subprocess
                published = subprocess.run(["git", "cat-file", "-e", "origin/main:" + str(path.relative_to(ROOT))], cwd=ROOT, capture_output=True)
                if published.returncode == 0:
                    parser.error("Published migration/contract is immutable; add a new versioned snapshot")
            path.write_text(expected)
        elif not path.exists() or path.read_text() != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        parser.exit(1, "Approval limit drift: " + ", ".join(stale) + "\nRun --write for an unpublished migration; deployed schemas need a new forward migration.\n")
    print("Approval size consumers generated." if args.write else "Approval size consumers match the canonical manifest.")

if __name__ == "__main__":
    main()
