-- The workspace flush routes (`/api/internal/workspace-incarnations/:id/flushes/*`)
-- run WorkspaceFlushService on the system pool, whose login role is a member
-- of g5_app. A guest-reported block (`fail`, FLUSH_TOO_LARGE) records the
-- block on the incarnation and notifies the workspace owner in the same
-- transaction, but only g5_tenant held privileges on public.notifications
-- (001_lean_baseline.sql), so every first report of a fingerprint failed with
-- "permission denied for table notifications" and the guest retried a 503
-- indefinitely. Grant the system role the same access the tenant role holds;
-- the table has no row-level security, and the service inserts one row for
-- the current owner only.
GRANT SELECT, INSERT ON TABLE public.notifications TO g5_app;
